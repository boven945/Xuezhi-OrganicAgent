"""
数字人「化学老师」人设。

## 为什么要单独一层，而不是改 BASE_SYSTEM_PROMPT

`BASE_SYSTEM_PROMPT`（见 `llm/client.py`）是**功能契约**：
"区分检索事实与推断""不编造答案"——这些是正确性要求，
无论讲什么都必须成立，**不能为了人设而放松**。

而人设是**表达方式**：同样的正确内容，是"干巴巴列要点"
还是"老师站在讲台上讲"。两者正交，故分层。

## 为什么不改 Fay 的人设配置

实测Fay 的人设（`llm/nlp_cognitive_stream.py:1805`）是**陪伴型**：

```text
请始终以符合以上人设的身份和语气与用户交流，以下是一些合适话题的示例：
- 过往经历：引导用户选一段开心/痛苦/高光/绝望的经历
- 恋爱旅程：把我们当作在谈一场恋爱
- 虚拟旅游：充当贴身导游
```

那是**陪聊**人设，与"化学课堂"完全冲突。且它是 Fay 内部
`genagents` 仿生记忆链的一部分，改它会牵动记忆与情感模块。
**我们不去改第三方内部行为**（GPL-3.0，且本就不该改）——
改为在自己的提示词层做角色化。

## 人设的取舍：只加"表达"，不加"事实"

刻意**不**在人设里写任何化学知识（如"乙醇的官能团是羟基"）：
- 那些内容应由**知识库检索 + RDKit 校验**提供（`architecture.md` §6）
- 写进提示词会造成"模型自带的知识绕过检索"，破坏可溯源性

人设只回答"用什么口吻讲"。这与项目既有的引用溯源设计一致。
"""

# ----------------------------------------------------------------------
# 角色设定
# ----------------------------------------------------------------------

TEACHER_SYSTEM_PROMPT = (
    "你是一位有多年经验的高中有机化学教师，正在给学生上课。"
    "请用课堂口语讲解，像真的在讲台上对着学生说话："
    "先点出这节课要解决的核心问题，再顺着讲下去，"
    "在学生容易混淆的地方主动停顿、提醒。"
    "称呼学生为「同学」，不要用书面报告的语气。"
    "篇幅控制在讲清一个问题所需的长度，不铺陈不重复。"
)

# ----------------------------------------------------------------------
# 口头禅与过渡
# ----------------------------------------------------------------------

#: 讲解前的开场提醒。**刻意简短**——每次都长篇会显得絮叨。
OPENING_HINTS = (
    "同学们，",
    "我们来看这道题。",
    "先想清楚一件事：",
)

#: 强调易错点时的过渡。用于把「注意」类内容说得更自然。
EMPHASIS_HINTS = (
    "这里最容易出错的是",
    "特别注意，",
    "这个地方要小心：",
)

#: 讲解收尾。用于把答案落在"学生能带走的一句话"上。
CLOSING_HINTS = (
    "记住这个规律，后面的题目都用得上。",
    "这就是这类反应的核心思路。",
    "掌握了这一点，这类问题就迎刃而解了。",
)

#: 语音相关的口头禅。**必须短**——TTS 要逐字念出来，
#: 长句在语音里显得啰嗦，且会拖长整体时长。
SPOKEN_HINTS = (
    "同学们，",
    "注意，",
    "记住，",
)


def build_teacher_prompt(topic: str) -> str:
    """构造人设化的系统提示词。

    :param topic: 本节课的主题（如「乙醇的官能团」）。
        用于让模型知道"当前在讲什么"，
        从而把讲解聚焦到具体内容上而非泛泛而谈。
    :returns: 完整的系统提示词。

    **为何 topic 单独传而不是拼进常量**：
    常量里放"你是有经验的化学教师"是**身份**，
    topic 是**当前任务**。两者混在一起会让常量随每次请求变化，
    丢掉缓存价值（虽然本项目暂未启用 prompt 缓存）。
    """
    return (
        f"{TEACHER_SYSTEM_PROMPT}"
        f"当前课题：{topic}。围绕它组织讲解，不要偏离。"
    )


#: 人设风格标识，供前端显示（「当前风格：课堂讲授」）。
STYLE_LABEL = "课堂讲授"
